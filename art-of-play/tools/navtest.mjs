// Drives the real keyboard in real-time mode and asserts presenter navigation.
import { createRequire } from 'module'
const require = createRequire(import.meta.url)
let pw
try { pw = require('playwright') } catch { pw = require('/opt/node-tools/node_modules/playwright') }
const url = process.argv[2]
const b = await pw.chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const p = await b.newPage({ viewport: { width: 1280, height: 720 } })
const errors = []
p.on('pageerror', (e) => errors.push(e.message))
await p.goto(`${url}?q=low`)
await p.waitForFunction(() => window.__aop && window.__aop.ready, null, { timeout: 60000 })
const st = () => p.evaluate(() => window.__aop.state())
const wait = (ms) => p.waitForTimeout(ms)
const results = []
const check = (name, ok, info) => { results.push({ name, ok, info }); console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}  ${info ?? ''}`) }
const untilIdle = async (max = 60000) => { const t0 = Date.now(); while ((await st()).playing && Date.now() - t0 < max) await wait(100) }

let s = await st()
check('starts on scene 1 hold 0 (void)', s.scene === 1 && s.beat === 0 && s.label === 'void', JSON.stringify({ scene: s.scene, label: s.label }))
await p.keyboard.press('ArrowRight'); await wait(400)
s = await st()
check('Right arrow starts beat 1', s.playing === true, `playing=${s.playing}`)
await p.keyboard.press('ArrowRight'); await wait(200)
s = await st()
check('Right during a beat completes it immediately', !s.playing && s.label === 'line', `label=${s.label}`)
await p.keyboard.press('Space'); await wait(300)
await p.keyboard.press('Space'); await wait(200)
s = await st()
check('Space advances (and completes)', s.label === 'matter', `label=${s.label}`)
await p.keyboard.press('PageDown'); await untilIdle()
s = await st()
check('PageDown advances and plays to the next hold', s.label === 'question' && !s.playing, `label=${s.label}`)
await p.keyboard.press('ArrowLeft'); await wait(200)
s = await st()
check('Left arrow returns to the previous hold instantly', s.label === 'matter' && !s.playing, `label=${s.label}`)
await p.keyboard.press('PageUp'); await wait(200)
s = await st()
check('PageUp goes back', s.label === 'line', `label=${s.label}`)
await p.keyboard.press('ArrowRight'); await wait(500)
await p.keyboard.press('ArrowLeft'); await wait(200)
s = await st()
check('Left during a beat abandons it and returns to its start hold', s.label === 'line' && !s.playing, `label=${s.label}`)
await p.keyboard.press('r'); await wait(300)
s = await st()
check('R replays the scene from its first hold', s.scene === 1 && s.beat === 0, `beat=${s.beat}`)
await p.keyboard.press('m'); await wait(200)
let muted = await p.evaluate(() => document.querySelector('.indicator')?.textContent.includes('muted'))
check('M mutes (indicator shows muted)', muted === true)
await p.keyboard.press('m'); await wait(200)
muted = await p.evaluate(() => document.querySelector('.indicator')?.textContent.includes('muted'))
check('M unmutes', muted === false)
const audioState = await p.evaluate(() => window.__aop && document.querySelector('canvas') && (window.AudioContext ? 'available' : 'none'))
check('Web Audio available', audioState === 'available')
await p.keyboard.press('2'); await wait(400)
s = await st()
check('Number key jumps to scene 2', s.scene === 2 && s.label === 'apart', `scene=${s.scene} label=${s.label}`)
await p.keyboard.press('ArrowLeft'); await wait(400)
s = await st()
check('Left from first hold of scene 2 returns to last hold of scene 1', s.scene === 1 && s.label === 'suits', `scene=${s.scene} label=${s.label}`)
await p.keyboard.press('ArrowRight'); await untilIdle()
s = await st()
check('Exit beat carries into scene 2 and plays its intro to the first hold', s.scene === 2 && s.label === 'apart' && !s.playing, `scene=${s.scene} label=${s.label}`)
await p.keyboard.press('f'); await wait(500)
const fs = await p.evaluate(() => !!document.fullscreenElement)
check('F toggles fullscreen', fs === true, `fullscreen=${fs}`)
await p.keyboard.press('f'); await wait(500)
const fs2 = await p.evaluate(() => !!document.fullscreenElement)
check('F exits fullscreen', fs2 === false, `fullscreen=${fs2}`)
check('no page errors', errors.length === 0, errors.join(' | '))
await b.close()
const failed = results.filter((r) => !r.ok).length
console.log(`\n${results.length - failed}/${results.length} passed`)
process.exit(failed ? 1 : 0)

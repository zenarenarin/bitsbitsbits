// Real touch events on an emulated phone: begin, stick, jump, pull, pause/resume, result and replay.
const { chromium } = require('/opt/node-tools/node_modules/playwright');
const out = process.argv[2] || '.';
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const bc = await browser.newContext({ viewport: { width: 402, height: 874 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
  const page = await bc.newPage();
  const errs = []; page.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
  await page.goto('http://localhost:8766/dev/index.html');
  await page.waitForFunction(() => window.__ready);
  const cdp = await bc.newCDPSession(page);
  const touch = (type, pts) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: pts.map(p => ({ x: p.x, y: p.y, id: p.id })) });
  let pass = 0, total = 0; const check = (n, c, i) => { total++; if (c) pass++; console.log((c ? 'PASS ' : 'FAIL ') + n + (i ? ' ' + JSON.stringify(i) : '')); };
  const L = f => page.evaluate(f);
  await touch('touchStart', [{ x: 200, y: 400, id: 1 }]); await touch('touchEnd', []);
  await page.waitForTimeout(100);
  check('a tap on the title begins the run', (await L(() => window.__ll.mode)) === 'play' && (await L(() => window.__starts)) === 1);
  const x0 = await L(() => window.__ll.player.x);
  await touch('touchStart', [{ x: 80, y: 720, id: 2 }]); await touch('touchMove', [{ x: 130, y: 720, id: 2 }]);
  await page.waitForTimeout(500);
  const x1 = await L(() => window.__ll.player.x);
  const b = await L(() => window.__ll.btn);
  await touch('touchStart', [{ x: 130, y: 720, id: 2 }, { x: b.jump.x, y: b.jump.y, id: 3 }]);
  await page.waitForTimeout(60);
  const st = await L(() => ({ s: window.__ll.player.state, vy: window.__ll.player.vy }));
  await touch('touchEnd', []);
  check('the left stick runs, the jump button jumps while running (multitouch)', x1 > x0 + 1 && st.s === 'air', { x0, x1, st });
  await page.screenshot({ path: out + '/t1_running.png' });
  await L(() => { const l = window.__ll; l.player.reset(56.2, 0, 1); l.R.follow(l.player, 1, true); });
  await page.waitForTimeout(150);
  await touch('touchStart', [{ x: b.act.x, y: b.act.y, id: 4 }]); await touch('touchEnd', []);
  await page.waitForTimeout(700);
  await page.screenshot({ path: out + '/t2_pulled.png' });
  check('the pull button unrolls the awning in reach', (await L(() => window.__ll.level.awnings[0].t)) > 0.9);
  await touch('touchStart', [{ x: b.pause.x, y: b.pause.y, id: 5 }]); await touch('touchEnd', []);
  await page.waitForTimeout(100);
  await page.screenshot({ path: out + '/t3_pause.png' });
  check('pause opens the menu', (await L(() => window.__ll.mode)) === 'paused');
  const rb = await L(() => { const e = document.querySelector('.ll-b'); const r = e.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; });
  await page.touchscreen.tap(rb.x, rb.y);
  await page.waitForTimeout(100);
  check('resume returns to play', (await L(() => window.__ll.mode)) === 'play');
  await L(() => { const l = window.__ll; l.player.reset(141.5, 0, 1); l.R.follow(l.player, 1, true); });
  await page.keyboard.down('ArrowRight'); await page.waitForTimeout(800); await page.keyboard.up('ArrowRight');
  await page.waitForTimeout(500);
  await page.screenshot({ path: out + '/t4_result.png' });
  check('reaching the arch ends the run with a result', (await L(() => window.__ll.mode)) === 'result' && !!(await L(() => window.__complete)));
  const again = await L(() => { const e = [...document.querySelectorAll('.ll-b')].find(b => /again/i.test(b.textContent)); const r = e.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; });
  await page.touchscreen.tap(again.x, again.y);
  await page.waitForTimeout(100);
  check('run again starts a new attempt at once', (await L(() => window.__ll.mode)) === 'play' && (await L(() => window.__starts)) === 2 && (await L(() => window.__ll.runT)) < 1);
  console.log(pass + '/' + total + ' touch checks'); if (errs.length) console.log(errs.join('\n'));
  await browser.close();
})();

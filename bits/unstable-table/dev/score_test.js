// Unit checks for the scoring rules in src/03b_score.js. Run: node dev/score_test.js
const fs = require('fs'), path = require('path');
const src = ['00_util.js', '03b_score.js'].map(f => fs.readFileSync(path.join(__dirname, '../src', f), 'utf8')).join('\n');
const { balanceBonus, streakMultiplier, placementScore, SCORING } = new Function(src + '\nreturn { balanceBonus, streakMultiplier, placementScore, SCORING };')();
let fails = 0;
const eq = (name, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); console.log((ok ? 'PASS ' : 'FAIL ') + name + (ok ? '' : `  got ${JSON.stringify(got)} want ${JSON.stringify(want)}`)); if (!ok) fails++; };
eq('level table: +100', balanceBonus(0), 100);
eq('2.0 deg: +100', balanceBonus(2), 100);
eq('-1.9 deg (sign ignored): +100', balanceBonus(-1.9), 100);
eq('2.01 deg: +70', balanceBonus(2.01), 70);
eq('4 deg: +70', balanceBonus(4), 70);
eq('5.5 deg: +40', balanceBonus(-5.5), 40);
eq('6 deg: +40', balanceBonus(6), 40);
eq('6.1 deg: 0', balanceBonus(6.1), 0);
eq('multipliers by streak 1..7', [1, 2, 3, 4, 5, 6, 7].map(streakMultiplier), [1, 1.25, 1.5, 1.75, 2, 2, 2]);
eq('first placement, level', placementScore(0.5, 1), { base: 100, bonus: 100, mult: 1, total: 200 });
eq('third in a row at 3 deg', placementScore(3, 3), { base: 100, bonus: 70, mult: 1.5, total: 255 });
eq('fifth in a row at 8 deg', placementScore(-8, 5), { base: 100, bonus: 0, mult: 2, total: 200 });
eq('second in a row at 5 deg', placementScore(5, 2), { base: 100, bonus: 40, mult: 1.25, total: 175 });
eq('perfect bonus', SCORING.perfect, 150);
console.log(fails ? `\n${fails} FAILED` : '\nall passed');
process.exit(fails ? 1 : 0);

// Solve the designed levels offline and write src/08_levels_data.js (the proof arrangements).
const fs = require('fs'), path = require('path');
const { World, Catalog, Packer, Levels } = require('./load')();
const out = [];
for (const [i, d] of Levels.DEFS.entries()) {
  const t = Date.now(); let best = null;
  for (let k = 0; k < 4; k++) {
    const pz = Packer.runSync(Packer.puzzleGen(d.items.map(id => ({ id })), { H: d.H, seed: d.seed + k * 13, slack: d.slack, searchSteps: 7, maxOrient: 10 }));
    if (pz.ok && (!best || pz.W * pz.D < best.W * best.D)) best = pz;
  }
  if (!best) { console.log('FAILED level', i + 1, d.name); process.exit(1); }
  const v = Packer.verify(best);
  const vol = best.solution.reduce((s, p) => s, 0);
  console.log(`${String(i + 1).padStart(2)} ${d.name.padEnd(20)} ${d.items.length} items  drawer ${best.W} x ${best.D} x ${best.H}  verified ${v.ok}  ${Date.now() - t} ms`);
  out.push({ W: best.W, D: best.D, H: best.H, items: best.items, solution: best.solution });
}
const src = '// Generated by dev/gen_levels.js: designed drawers with their proof arrangements.\nconst LEVEL_DATA = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', '08_levels_data.js'), src);
console.log('wrote', src.length, 'bytes');

// Validate the 12 journey routes once and bake their plans into src/04_plans.js,
// so phones rebuild them instantly. Re-run after changing the generator.
const fs = require('fs'), path = require('path');
const S = require('./simload');
const plans = [];
for (const spec of S.ROUTES) {
  const W = S.buildRoute(spec);
  plans.push(S.routePlan(W));
  // the baked plan must rebuild the identical route
  const W2 = S.buildRoute(spec, { plan: plans[plans.length - 1] });
  const sig = w => w.surfaces.map(s => { const o = {}; s.pose(1.234, o); return o.x.toFixed(3) + ',' + o.y.toFixed(3); }).join(';');
  if (sig(W) !== sig(W2) || W.brisk !== W2.brisk || W.letters.length !== W2.letters.length) throw new Error('plan mismatch on route ' + (spec.index + 1));
  console.log('route', spec.index + 1, 'ok', 'brisk', W.brisk, 'letters', W.letters.length);
}
const out = '// Generated by dev/bake.js from the route generator. Do not edit by hand.\nconst ROUTE_PLANS = ' + JSON.stringify(plans) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', '04_plans.js'), out);
console.log('wrote src/04_plans.js', out.length, 'bytes');

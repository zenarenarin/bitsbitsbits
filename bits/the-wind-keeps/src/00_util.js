  const i = Math.floor(x), f = x - i;
  const h = n => { let t = Math.imul((n + seed * 374761393) | 0, 668265263); t = Math.imul(t ^ (t >>> 13), 1274126177); return ((t ^ (t >>> 16)) >>> 0) / 4294967296; };

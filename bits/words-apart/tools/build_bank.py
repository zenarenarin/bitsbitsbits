"""Build src/01_bank.js from tools/puzzles.txt.

For every puzzle, the accepted answers are every word in BOTH reference dictionaries
(npm `word-list` and npm `an-array-of-english-words`) that shares the puzzle's first letter,
last letter and length, minus a small blocklist. The game never consults a dictionary at
runtime: it only accepts words baked into this reviewed bank.

Usage (from bits/words-apart):
  npm i --prefix <tools-dir> word-list@2 an-array-of-english-words
  pip install wordfreq
  python3 tools/build_bank.py <tools-dir>/node_modules
"""
import json, re, sys, os
from wordfreq import zipf_frequency as zf

LEN = {1: (3, 4), 2: (4, 5), 3: (5, 6), 4: (6, 8), 5: (7, 9)}
# Never celebrated on screen, even when a dictionary lists them.
BLOCK = set('''COON KIKE TWAT RAPE RAPED RAPES WHORE WHORES PORNO SLUT SLUTS CUNT CUNTS FAG FAGS FAGGOT DYKE DYKES
NIGGER NIGGA SPIC SPICS CHINK GOOK GOOKS WETBACK RETARD TRANNY PAKI DAGO WOP WOPS FUCK FUCKS FUCKED SHIT SHITS
PUSSY HORNY JIZZ SPUNK BOLLOCKS WANKER WANK TWATS RAPIST NAZI'''.split())

def main(nm):
    a = set(l.strip().upper() for l in open(os.path.join(nm, 'word-list/words.txt')))
    b = set(w.upper() for w in json.load(open(os.path.join(nm, 'an-array-of-english-words/index.json'))))
    both = {w for w in a & b if re.fullmatch('[A-Z]+', w)}
    out, seen, errors = {1: [], 2: [], 3: [], 4: [], 5: []}, set(), []
    for line in open(os.path.join(os.path.dirname(__file__), 'puzzles.txt')):
        line = line.strip()
        if not line or line.startswith('#'): continue
        lv, ans, hint = [x.strip() for x in line.split('|')]
        lv = int(lv)
        lo, hi = LEN[lv]
        if not (lo <= len(ans) <= hi): errors.append(f'{ans}: length {len(ans)} outside level {lv} range {lo}-{hi}')
        if ans in seen: errors.append(f'{ans}: duplicate')
        if ans not in both: errors.append(f'{ans}: not in both reference dictionaries')
        stem = ans[:max(4, len(ans) - 3)].lower()
        if stem in hint.lower(): errors.append(f'{ans}: hint gives the answer away')
        seen.add(ans)
        acc = sorted((w for w in both if len(w) == len(ans) and w[0] == ans[0] and w[-1] == ans[-1] and w not in BLOCK),
                     key=lambda w: (-zf(w.lower(), 'en'), w))
        acc.remove(ans); acc.insert(0, ans)
        for w in acc:
            assert w[0] == ans[0] and w[-1] == ans[-1] and len(w) == len(ans)
        fam = zf(ans.lower(), 'en')
        out[lv].append({
            'id': f'level_{lv:02d}_{len(out[lv]) + 1:03d}', 'startLetter': ans[0], 'endLetter': ans[-1], 'length': len(ans),
            'answer': ans, 'acceptedAnswers': acc, 'hint': hint,
            # 1–5 by level, plus a familiarity score (Zipf frequency: 7 is "the", 3 is uncommon) for tuning.
            'difficulty': lv, 'familiarity': round(fam, 2), 'validation': 'verified'})
    if errors:
        print('\n'.join(errors)); sys.exit(1)
    # Compact form: accepted answers ride as one space-separated string to keep the bundle small.
    rows = []
    for lv in range(1, 6):
        for p in out[lv]:
            q = dict(p); q['acceptedAnswers'] = ' '.join(p['acceptedAnswers']); rows.append(q)
    js = ('// Generated by tools/build_bank.py from tools/puzzles.txt. Do not edit by hand.\n'
          '// acceptedAnswers is a space-separated list; the primary answer is always first.\n'
          'const PUZZLE_BANK_RAW = ' + json.dumps(rows, separators=(',', ':')) + ';\n')
    path = os.path.join(os.path.dirname(__file__), '..', 'src', '01_bank.js')
    open(path, 'w').write(js)
    print('levels', {k: len(v) for k, v in out.items()}, 'accepted words', sum(len(p['acceptedAnswers']) for v in out.values() for p in v), 'bytes', len(js))

if __name__ == '__main__':
    main(sys.argv[1])
